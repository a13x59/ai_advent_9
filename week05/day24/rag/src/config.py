"""Параметры ретрива, фильтрации и реранкинга (День 23).

Все значения можно переопределять через CLI / HTTP / вызовы функций,
здесь — единые значения по умолчанию, чтобы пороги не были «размазаны»
по коду.
"""
from __future__ import annotations

# Топ-K до и после второго этапа.
TOP_K_CANDIDATES = 20   # сколько кандидатов брать ДО фильтрации/реранкинга
TOP_K_FINAL = 5         # сколько возвращать ПОСЛЕ второго этапа

# Порог отсечения (filter-режим): чанк с cosine similarity ниже MIN_SCORE
# считается нерелевантным и отбрасывается.
MIN_SCORE = 0.5

# Относительный запас от лучшего результата (устойчивость к масштабу score):
# если > 0, дополнительно сохраняем чанки с score >= max_score - MAX_SCORE_MARGIN.
# 0.0 — только абсолютный порог (калибруется sweep-ом на тест-сете).
MAX_SCORE_MARGIN = 0.0

# Порог релевантности для режима «не знаю» (День 24). Отдельный от MIN_SCORE
# (тот отсекает отдельные чанки в filter-режиме), а здесь — гейт на весь ответ:
# если лучший cosine-score итоговых чанков ниже RELEVANCE_THRESHOLD (или чанков
# нет вовсе), ассистент обязан детерминированно сказать «не знаю» и попросить
# уточнение, не вызывая LLM.
RELEVANCE_THRESHOLD = 0.5

# Лексическая эвристика (rerank-режим): вес лексического пересечения
# запрос↔чанк при fusion с косинусным сходством (0..1).
LEX_WEIGHT = 0.3

# MMR: баланс релевантность/разнообразие (1.0 — только релевантность,
# без учёта дублей; 0.0 — только разнообразие).
MMR_LAMBDA = 0.7

# Режимы пайплайна. «rewrite» применяется ДО ретрива (LLM-переформулировка),
# «filter»/«rerank» — второй этап ПОСЛЕ ретрива.
MODES = ["baseline", "rewrite", "filter", "rewrite+filter", "rerank"]

# Сетка порогов для sweep-анализа (подбор MIN_SCORE).
SWEEP_THRESHOLDS = [0.0, 0.30, 0.35, 0.40, 0.45, 0.50, 0.55, 0.60, 0.65, 0.70]
