"""Промпт-шаблоны для RAG-QA кейса.

baseline — точная копия текущих шаблонов из rag/src/qa.py (RAG_SYSTEM +
build_rag_prompt), чтобы «до оптимизации» было сравнимо с Днём 28.

variant — оптимизированный шаблон под кейс (День 29, п.5): явный язык,
краткость, более жёсткая привязка к цитатам. Сравнивается с baseline через
тот же бенчмарк.
"""
from __future__ import annotations

BASELINE_SYSTEM = (
    "Ты — ассистент, отвечающий строго на основе предоставленного контекста из "
    "базы знаний. Следуй обязательному формату ответа (секции «Ответ», «Источники», "
    "«Цитаты»). Каждое утверждение ответа помечай ссылкой [n] и подтверждай дословной "
    "цитатой; источники указывай с source, section и chunk_id. Без дословной цитаты "
    "утверждение писать нельзя."
)


def build_rag_prompt(question: str, chunks: list[dict]) -> str:
    """Baseline: точная копия rag/src/qa.py::build_rag_prompt."""
    if not chunks:
        context = "(релевантные фрагменты не найдены)"
    else:
        blocks = []
        for i, c in enumerate(chunks, 1):
            title = c.get("title") or ""
            section = c.get("section") or ""
            src = c.get("source") or ""
            cid = c.get("chunk_id") or ""
            header = f"[{i}] {title}" + (f" — {section}" if section else "")
            blocks.append(
                f"{header}\nИсточник: {src}\nchunk_id: {cid}\n{c.get('text', '')}"
            )
        context = "\n\n".join(blocks)

    return (
        "Ответь на вопрос пользователя, используя ТОЛЬКО приведённый ниже контекст "
        "(фрагменты из базы знаний).\n"
        "\n"
        "ФОРМАТ ОТВЕТА — строго по шаблону (три секции):\n"
        "\n"
        "## Ответ\n"
        "<краткий ответ по контексту; каждое утверждение заканчивай ссылкой [n]>\n"
        "\n"
        "## Источники\n"
        "- [n] source: <путь> | section: <раздел> | chunk_id: <id>\n"
        "(по одной строке на каждый использованный фрагмент)\n"
        "\n"
        "## Цитаты\n"
        "- [n] «<дословный фрагмент из соответствующего чанка>»\n"
        "(по цитате на каждое фактическое утверждение из «Ответ»)\n"
        "\n"
        "Правила:\n"
        "- Отвечай только на основе контекста; не добавляй сведений, которых в нём нет.\n"
        "- Каждое утверждение в «Ответ» обязательно помечай ссылкой [n] на фрагмент контекста.\n"
        "- Любое утверждение без дословной цитаты недопустимо: либо процитируй его, либо убери из ответа.\n"
        "- В «Цитаты» приведи ДОСЛОВНЫЙ фрагмент для каждого утверждения из «Ответ» (не пересказ).\n"
        "- Номер [n] должен совпадать с номером фрагмента в контексте.\n"
        "- В «Источники» указывай source, section и chunk_id именно из заголовка фрагмента.\n"
        "- Если в контексте нет ответа на вопрос — так и скажи и попроси уточнить вопрос.\n"
        "\n"
        f"Контекст:\n{context}\n\n"
        f"Вопрос: {question}"
    )


VARIANT_SYSTEM = (
    "Ты — ассистент по русскоязычным материалам о NLP/ML. Отвечай ТОЛЬКО на "
    "русском языке и ТОЛЬКО на основе предоставленного контекста. Строго следуй "
    "формату из трёх секций «Ответ», «Источники», «Цитаты»: каждое утверждение "
    "помечай ссылкой [n] и подтверждай дословной цитатой, указывая source, section "
    "и chunk_id. Не добавляй ничего сверх контекста."
)


def build_variant_prompt(question: str, chunks: list[dict]) -> str:
    """Variant: более краткий и жёсткий шаблон под RAG-QA кейс."""
    if not chunks:
        context = "(релевантные фрагменты не найдены)"
    else:
        blocks = []
        for i, c in enumerate(chunks, 1):
            title = c.get("title") or ""
            section = c.get("section") or ""
            src = c.get("source") or ""
            cid = c.get("chunk_id") or ""
            header = f"[{i}] {title}" + (f" — {section}" if section else "")
            blocks.append(f"{header} | {src} | {cid}\n{c.get('text', '')}")
        context = "\n\n".join(blocks)

    return (
        "Ответь на вопрос по-русски, используя ТОЛЬКО приведённый контекст.\n"
        "\n"
        "Формат ответа (строго):\n"
        "## Ответ\n"
        "2–4 предложения; каждое утверждение заканчивай ссылкой [n].\n"
        "\n"
        "## Источники\n"
        "- [n] source: <путь> | section: <раздел> | chunk_id: <id>\n"
        "\n"
        "## Цитаты\n"
        "- [n] «<дословный фрагмент>»\n"
        "\n"
        "Правила:\n"
        "- Только факты из контекста, без домысливания.\n"
        "- Каждая ссылка [n] в «Ответ» обязана иметь дословную цитату в «Цитаты».\n"
        "- Номер [n] = номер фрагмента в контексте; source/section/chunk_id — из его заголовка.\n"
        "- Нет ответа в контексте — напиши «не знаю» и попроси уточнить.\n"
        "\n"
        f"Контекст:\n{context}\n\n"
        f"Вопрос: {question}"
    )


TEMPLATES = {
    "baseline": {"system": BASELINE_SYSTEM, "build": build_rag_prompt},
    "variant": {"system": VARIANT_SYSTEM, "build": build_variant_prompt},
}
